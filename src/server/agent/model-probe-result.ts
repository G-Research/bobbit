import { sanitizeModelErrorText } from "./model-error-sanitizer.js";

export type ModelProbeErrorCode = "model_not_found" | "authentication_failed" | "rate_limited";
export type ModelProbeUpstreamStatus = 401 | 403 | 404 | 429;

export interface ModelProbeSuccess {
	ok: true;
	modelResolved: string;
	latencyMs: number;
}

export interface ModelProbeFailure {
	ok: false;
	modelResolved?: string;
	latencyMs?: number;
	error: string;
	status?: ModelProbeUpstreamStatus;
	code?: ModelProbeErrorCode;
}

export type ModelProbeResult = ModelProbeSuccess | ModelProbeFailure;

const ERROR_CODES: Record<ModelProbeUpstreamStatus, ModelProbeErrorCode> = {
	401: "authentication_failed",
	403: "authentication_failed",
	404: "model_not_found",
	429: "rate_limited",
};

function trackedStatus(value: unknown): ModelProbeUpstreamStatus | undefined {
	return typeof value === "number" && value in ERROR_CODES
		? value as ModelProbeUpstreamStatus
		: undefined;
}

/**
 * Pi's current Anthropic SDK errors begin with its HTTP status (for example,
 * `401 Unauthorized`). Older Pi transport errors use the structured envelope
 * below. Both prefixes are generated by Pi, so they are trustworthy; never
 * scan the remaining provider-controlled message for status-looking numbers.
 */
function statusFromTrustedPiError(error: unknown): ModelProbeUpstreamStatus | undefined {
	if (!(error instanceof Error)) return undefined;
	const leadingStatus = /^(\d{3})(?:\s|$)/.exec(error.message);
	if (leadingStatus) return trackedStatus(Number(leadingStatus[1]));

	const legacyEnvelope = /^HTTP request failed\. status=(\d+); url=https?:\/\/[^;\s]+; body=/.exec(error.message);
	return trackedStatus(legacyEnvelope ? Number(legacyEnvelope[1]) : undefined);
}

/** Classify only an anchored status emitted by Pi, never provider response text. */
export function classifyModelProbeError(error: unknown): { status?: ModelProbeUpstreamStatus; code?: ModelProbeErrorCode } {
	const status = statusFromTrustedPiError(error);
	return status ? { status, code: ERROR_CODES[status] } : {};
}

/**
 * Build a probe failure from an HTTP response whose status was observed directly
 * by Bobbit. This is intentionally separate from text classification: a gateway
 * response status is trusted even though its body is not.
 */
export function modelProbeFailureFromHttpStatus(
	status: number,
	details: Pick<ModelProbeFailure, "modelResolved" | "latencyMs"> = {},
): ModelProbeFailure {
	const tracked = trackedStatus(status);
	return {
		ok: false,
		...details,
		error: `Gateway returned HTTP ${status}`,
		...(tracked ? { status: tracked, code: ERROR_CODES[tracked] } : {}),
	};
}

export function modelProbeFailure(
	error: unknown,
	details: Pick<ModelProbeFailure, "modelResolved" | "latencyMs"> = {},
): ModelProbeFailure {
	const message = sanitizeModelErrorText(error) || "Request failed";
	return { ok: false, ...details, error: message, ...classifyModelProbeError(error) };
}
